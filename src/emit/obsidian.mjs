// Emits an Obsidian theme (theme.css + manifest.json) from a palette.
// Accent-hue controls (--accent-h/s/l) drive every native accent widget;
// the rest pins the core surfaces, text, tabs and both syntax class
// families (.cm-* live preview, .token.* reading mode).
import { alpha, lighten, hslOf } from '../lib/color.mjs'

const h = (c) => c.hex6().toLowerCase()
const a8 = (c) => c.hex8().toLowerCase()

export function emitObsidianCss(pal) {
  const { h: ah, s: as, l: al } = hslOf(pal.C.accent)
  const hoverTint = alpha(pal.C.accent, 0.08, 'obsidian hover tint of accent')
  const activeTint = alpha(pal.C.accent, 0.14, 'obsidian active tint of accent')
  const tagBg = alpha(pal.C.accent, 0.16, 'obsidian tag background tint')
  const shadow = alpha(pal.C.bg, 0.5, 'obsidian modal shadow')
  const cover = alpha(pal.C.bg, 0.8, 'obsidian modal cover')

  const syntax = [
    ['keyword', pal.tokens.keyword], ['string', pal.tokens.string],
    ['number', pal.tokens.number], ['comment', pal.tokens.comment],
    ['property', pal.tokens.property], ['operator', pal.tokens.operator],
    ['tag', pal.tokens.tag], ['link', pal.tokens.link],
  ]
  const cmOnly = [
    ['def', pal.tokens.fn], ['variable', pal.tokens.variable],
    ['atom', pal.tokens.number], ['builtin', pal.tokens.type],
    ['qualifier', pal.tokens.type], ['meta', pal.text.dim],
    ['url', pal.tokens.link], ['formatting', pal.text.dim],
  ]
  const tokenOnly = [
    ['function', pal.tokens.fn], ['attr-name', pal.tokens.attribute],
    ['title', pal.tokens.heading], ['class-name', pal.tokens.type],
    ['boolean', pal.tokens.number], ['constant', pal.tokens.number],
  ]

  const L = []
  L.push('/* Generated by build.mjs from src/palettes/ — DO NOT EDIT.')
  L.push(` * ${pal.label} (${pal.family}). Use with base theme: Dark. */`)
  L.push(`body {`)
  L.push(`  --accent-h: ${ah};`)
  L.push(`  --accent-s: ${as}%;`)
  L.push(`  --accent-l: ${al}%;`)
  L.push(`}`)
  L.push(``)
  L.push(`.theme-dark {`)
  L.push(`  color-scheme: dark;`)
  L.push(``)
  L.push(`  /* surfaces */`)
  L.push(`  --background-primary: ${h(pal.C.bg)};`)
  L.push(`  --background-primary-alt: ${h(pal.chrome.tabIdle)};`)
  L.push(`  --background-secondary: ${h(pal.chrome.panel)};`)
  L.push(`  --background-secondary-alt: ${h(pal.chrome.tab)};`)
  L.push(``)
  L.push(`  /* borders, hovers, overlays */`)
  L.push(`  --background-modifier-border: ${h(pal.line.panel)};`)
  L.push(`  --background-modifier-border-hover: ${h(pal.line.strong)};`)
  L.push(`  --background-modifier-border-focus: ${h(pal.accent.focus)};`)
  L.push(`  --background-modifier-hover: ${a8(hoverTint)};`)
  L.push(`  --background-modifier-active-hover: ${a8(activeTint)};`)
  L.push(`  --background-modifier-box-shadow: ${a8(shadow)};`)
  L.push(`  --background-modifier-cover: ${a8(cover)};`)
  L.push(``)
  L.push(`  /* semantic states */`)
  L.push(`  --background-modifier-success: ${a8(alpha(pal.C.success, 0.12, 'obsidian success tint'))};`)
  L.push(`  --background-modifier-error: ${a8(alpha(pal.C.error, 0.12, 'obsidian error tint'))};`)
  L.push(`  --background-modifier-error-hover: ${a8(alpha(pal.C.error, 0.2, 'obsidian error hover tint'))};`)
  L.push(`  --background-modifier-message: ${h(pal.chrome.titleBar)};`)
  L.push(`  --text-success: ${h(pal.C.success)};`)
  L.push(`  --text-error: ${h(pal.state.errorBright)};`)
  L.push(``)
  L.push(`  /* text */`)
  L.push(`  --text-normal: ${h(pal.text.normal)};`)
  L.push(`  --text-muted: ${h(pal.text.soft)};`)
  L.push(`  --text-faint: ${h(pal.text.ghost)};`)
  L.push(`  --text-on-accent: ${h(pal.text.onAccent)};`)
  L.push(`  --text-selection: ${a8(pal.alphaed.selection)};`)
  L.push(`  --text-highlight-bg: ${a8(pal.alphaed.lineHighlight)};`)
  L.push(``)
  L.push(`  /* title bar, tabs */`)
  L.push(`  --titlebar-background: ${h(pal.chrome.titleBar)};`)
  L.push(`  --titlebar-background-focused: ${h(pal.chrome.tab)};`)
  L.push(`  --titlebar-foreground: ${h(pal.text.dim)};`)
  L.push(`  --titlebar-foreground-inactive: ${h(pal.text.ghost)};`)
  L.push(`  --tab-text-color: ${h(pal.text.dim)};`)
  L.push(`  --tab-text-color-focused: ${h(pal.text.soft)};`)
  L.push(`  --tab-text-color-active: ${h(pal.text.bright)};`)
  L.push(`  --tab-background-active: ${h(pal.chrome.tab)};`)
  L.push(`  --tab-outline-color: ${h(pal.line.panel)};`)
  L.push(``)
  L.push(`  /* interactive controls */`)
  L.push(`  --interactive-normal: ${h(pal.chrome.input)};`)
  L.push(`  --interactive-hover: ${h(pal.chrome.hover)};`)
  L.push(`  --interactive-accent: ${h(pal.accent.button)};`)
  L.push(`  --interactive-accent-hover: ${h(pal.accent.buttonHover)};`)
  L.push(`  --interactive-success: ${h(pal.C.success)};`)
  L.push(`  --text-on-accent-inverted: ${h(pal.C.bg)};`)
  L.push(`  --scrollbar-thumb-bg: ${h(pal.line.indent)};`)
  L.push(`  --scrollbar-bg: transparent;`)
  L.push(`  --slider-thumb-background: ${h(pal.C.accent)};`)
  L.push(``)
  L.push(`  /* nav (file explorer) */`)
  L.push(`  --nav-item-color: ${h(pal.text.soft)};`)
  L.push(`  --nav-item-background-hover: ${h(pal.chrome.hover)};`)
  L.push(`  --nav-item-background-active: ${h(pal.chrome.selected)};`)
  L.push(`  --nav-item-background-selected: ${h(pal.chrome.selected)};`)
  L.push(``)
  L.push(`  /* editor extras */`)
  L.push(`  --inline-title-color: ${h(pal.tokens.heading)};`)
  for (let i = 1; i <= 6; i++) L.push(`  --h${i}-color: ${h(pal.tokens.heading)};`)
  L.push(`  --link-color: ${h(pal.tokens.link)};`)
  L.push(`  --link-color-hover: ${h(lighten(pal.C.info, 0.12, 'obsidian link hover'))};`)
  L.push(`  --link-unresolved-color: ${h(pal.text.ghost)};`)
  L.push(`  --blockquote-border-color: ${h(pal.line.strong)};`)
  L.push(`  --code-background: ${h(pal.chrome.sunken)};`)
  L.push(`  --tag-color: ${h(pal.accent.focus)};`)
  L.push(`  --tag-background: ${a8(tagBg)};`)
  L.push(`  --tag-background-hover: ${a8(activeTint)};`)
  L.push(`  --checkbox-color: ${h(pal.C.accent)};`)
  L.push(`  --checkbox-color-hover: ${h(pal.accent.buttonHover)};`)
  L.push(`  --checkbox-border-color: ${h(pal.line.strong)};`)
  L.push(`}`)
  L.push(``)
  L.push(`/* syntax: live preview (.cm-*) */`)
  for (const [name, color] of [...syntax, ...cmOnly]) {
    L.push(`.cm-${name} { color: ${h(color)}; }`)
  }
  L.push(`.cm-header { color: ${h(pal.tokens.heading)}; font-weight: 700; }`)
  L.push(`.cm-em { font-style: italic; }`)
  L.push(`.cm-strong { font-weight: 700; }`)
  L.push(``)
  L.push(`/* syntax: reading mode (.token.*) */`)
  for (const [name, color] of [...syntax, ...tokenOnly]) {
    L.push(`.token.${name} { color: ${h(color)}; }`)
  }
  L.push(``)
  return L.join('\n')
}

export function emitObsidianManifest(pal, version, author, authorUrl) {
  const manifest = {
    name: pal.label,
    version,
    minAppVersion: '1.0.0',
    author,
    authorUrl,
    fundingUrl: authorUrl,
  }
  return JSON.stringify(manifest, null, 2) + '\n'
}
