// Emits wezterm/<id>.lua: a module table dofile'd from ~/.wezterm.lua.
// Stable-release keys only (20240203): nightly-only keys are deliberately
// absent and a test enforces that. Every value is opaque #rrggbb — WezTerm
// ignores alpha everywhere except selection, so the VSCode alpha selection is
// pre-blended over the palette background by the palette (selectionOpaque).
const q = (c) => `'${c.hex6().toLowerCase()}'`
const SLOTS = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white']

const tabGroup = (name, bg, fg, extra = []) => [
  `    ${name} = {`,
  `      bg_color = ${q(bg)},`,
  `      fg_color = ${q(fg)},`,
  "      intensity = 'Normal',",
  "      underline = 'None',",
  `      italic = ${extra.includes('italic')},`,
  '      strikethrough = false,',
  '    },',
]

export function emitWezterm(pal) {
  const L = []
  L.push('-- Generated by build.mjs from src/palettes/ — DO NOT EDIT.')
  L.push('-- Stable WezTerm keys (20240203); nightly-only keys omitted; alpha pre-blended.')
  L.push('local M = {}')
  L.push(`M.name = '${pal.label}'`)
  L.push('M.colors = {')
  L.push(`  foreground = ${q(pal.text.normal)},`)
  L.push(`  background = ${q(pal.C.bg)},`)
  L.push(`  cursor_bg = ${q(pal.C.bright)},`)
  L.push(`  cursor_fg = ${q(pal.C.bg)},`)
  L.push(`  cursor_border = ${q(pal.C.bright)},`)
  L.push(`  selection_fg = ${q(pal.text.normal)},`)
  L.push(`  selection_bg = ${q(pal.selectionOpaque)}, -- pre-blended overlay selection @47% over the background`)
  L.push(`  split = ${q(pal.chrome.selected)},`)
  L.push(`  scrollbar_thumb = ${q(pal.line.indent)},`)
  L.push(`  compose_cursor = ${q(pal.C.error)},`)
  L.push(`  visual_bell = ${q(pal.C.muted)},`)
  L.push(`  copy_mode_active_highlight_bg = { Color = ${q(pal.chrome.selected)} },`)
  L.push(`  copy_mode_active_highlight_fg = { Color = ${q(pal.text.bright)} },`)
  L.push(`  copy_mode_inactive_highlight_bg = { Color = ${q(pal.chrome.hover)} },`)
  L.push(`  copy_mode_inactive_highlight_fg = { Color = ${q(pal.text.soft)} },`)
  L.push(`  quick_select_label_bg = { Color = ${q(pal.C.accent)} },`)
  L.push(`  quick_select_label_fg = { Color = ${q(pal.C.bg)} },`)
  L.push(`  quick_select_match_bg = { Color = ${q(pal.chrome.selected)} },`)
  L.push(`  quick_select_match_fg = { Color = ${q(pal.text.bright)} },`)
  L.push('  ansi = {')
  for (const s of SLOTS) L.push(`    ${q(pal.terminal16[s])}, -- ${s}`)
  L.push('  },')
  L.push('  brights = {')
  for (const s of SLOTS) L.push(`    ${q(pal.terminal16[`bright${s[0].toUpperCase()}${s.slice(1)}`])}, -- bright ${s}`)
  L.push('  },')
  L.push('  tab_bar = {')
  L.push(`    background = ${q(pal.chrome.panel)}, -- retro tab bar only; ignored by fancy`)
  L.push(`    inactive_tab_edge = ${q(pal.line.strong)},`)
  L.push(...tabGroup('active_tab', pal.chrome.tab, pal.text.bright))
  L.push(...tabGroup('inactive_tab', pal.chrome.tabIdle, pal.text.dim))
  L.push(...tabGroup('inactive_tab_hover', pal.chrome.hover, pal.text.normal, ['italic']))
  L.push(...tabGroup('new_tab', pal.chrome.panel, pal.text.dim))
  L.push(...tabGroup('new_tab_hover', pal.chrome.hover, pal.text.bright))
  L.push('  },')
  L.push('}')
  L.push('M.window_frame = {')
  L.push(`  active_titlebar_bg = ${q(pal.chrome.tab)},`)
  L.push(`  inactive_titlebar_bg = ${q(pal.chrome.tabIdle)},`)
  L.push(`  active_titlebar_fg = ${q(pal.text.normal)},`)
  L.push(`  inactive_titlebar_fg = ${q(pal.text.dim)},`)
  L.push(`  active_titlebar_border_bottom = ${q(pal.line.panel)},`)
  L.push(`  inactive_titlebar_border_bottom = ${q(pal.line.panel)},`)
  L.push(`  button_fg = ${q(pal.text.dim)},`)
  L.push(`  button_bg = ${q(pal.chrome.panel)},`)
  L.push(`  button_hover_fg = ${q(pal.text.bright)},`)
  L.push(`  button_hover_bg = ${q(pal.chrome.hover)},`)
  L.push('}')
  L.push('return M')
  return L.join('\n') + '\n'
}
