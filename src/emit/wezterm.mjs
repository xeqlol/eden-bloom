// Emits wezterm_theme.lua: a module table dofile'd from ~/.wezterm.lua.
// Stable-release keys only (20240203): nightly-only keys are deliberately
// absent and a test enforces that. Every value is opaque #rrggbb — WezTerm
// ignores alpha everywhere except selection, so the VSCode alpha selection is
// pre-blended over Midnight by the palette (selectionOpaque).
import { THEME_NAME } from '../reference.mjs'
import {
  C, chrome, text, line, state, terminal16, selectionOpaque,
} from '../palette.mjs'

const q = (c) => `'${c.hex6().toLowerCase()}'`
const SLOTS = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white']

const tabGroup = (name, bg, fg, extra = []) => [
  `    ${name} = {`,
  `      bg_color = ${q(bg)},`,
  `      fg_color = ${q(fg)},`,
  "      intensity = 'Normal',",
  "      underline = 'None',",
  `      italic = ${extra.includes('italic')},`,
  '      strikethrough = false,',
  '    },',
]

export function emitWezterm() {
  const L = []
  L.push('-- Generated by build.mjs from src/palette.mjs — DO NOT EDIT.')
  L.push('-- Stable WezTerm keys (20240203); nightly-only keys omitted; alpha pre-blended.')
  L.push('local M = {}')
  L.push(`M.name = '${THEME_NAME}'`)
  L.push('M.colors = {')
  L.push(`  foreground = ${q(text.normal)},`)
  L.push(`  background = ${q(C.Midnight)},`)
  L.push(`  cursor_bg = ${q(C.Sunlight)},`)
  L.push(`  cursor_fg = ${q(C.Midnight)},`)
  L.push(`  cursor_border = ${q(C.Sunlight)},`)
  L.push(`  selection_fg = ${q(text.normal)},`)
  L.push(`  selection_bg = ${q(selectionOpaque)}, -- pre-blended overlay selection @47% over Midnight`)
  L.push(`  split = ${q(chrome.selected)},`)
  L.push(`  scrollbar_thumb = ${q(line.indent)},`)
  L.push(`  compose_cursor = ${q(C.Coral)},`)
  L.push(`  visual_bell = ${q(C.Lavender)},`)
  L.push(`  copy_mode_active_highlight_bg = { Color = ${q(chrome.selected)} },`)
  L.push(`  copy_mode_active_highlight_fg = { Color = ${q(text.bright)} },`)
  L.push(`  copy_mode_inactive_highlight_bg = { Color = ${q(chrome.hover)} },`)
  L.push(`  copy_mode_inactive_highlight_fg = { Color = ${q(text.soft)} },`)
  L.push(`  quick_select_label_bg = { Color = ${q(C.Lilac)} },`)
  L.push(`  quick_select_label_fg = { Color = ${q(C.Midnight)} },`)
  L.push(`  quick_select_match_bg = { Color = ${q(chrome.selected)} },`)
  L.push(`  quick_select_match_fg = { Color = ${q(text.bright)} },`)
  L.push('  ansi = {')
  for (const s of SLOTS) L.push(`    ${q(terminal16[s])}, -- ${s}`)
  L.push('  },')
  L.push('  brights = {')
  for (const s of SLOTS) L.push(`    ${q(terminal16[`bright${s[0].toUpperCase()}${s.slice(1)}`])}, -- bright ${s}`)
  L.push('  },')
  L.push('  tab_bar = {')
  L.push(`    background = ${q(chrome.panel)}, -- retro tab bar only; ignored by fancy`)
  L.push(`    inactive_tab_edge = ${q(line.strong)},`)
  L.push(...tabGroup('active_tab', chrome.tab, text.bright))
  L.push(...tabGroup('inactive_tab', chrome.tabIdle, text.dim))
  L.push(...tabGroup('inactive_tab_hover', chrome.hover, text.normal, ['italic']))
  L.push(...tabGroup('new_tab', chrome.panel, text.dim))
  L.push(...tabGroup('new_tab_hover', chrome.hover, text.bright))
  L.push('  },')
  L.push('}')
  L.push('M.window_frame = {')
  L.push(`  active_titlebar_bg = ${q(chrome.tab)},`)
  L.push(`  inactive_titlebar_bg = ${q(chrome.tabIdle)},`)
  L.push(`  active_titlebar_fg = ${q(text.normal)},`)
  L.push(`  inactive_titlebar_fg = ${q(text.dim)},`)
  L.push(`  active_titlebar_border_bottom = ${q(line.panel)},`)
  L.push(`  inactive_titlebar_border_bottom = ${q(line.panel)},`)
  L.push(`  button_fg = ${q(text.dim)},`)
  L.push(`  button_bg = ${q(chrome.panel)},`)
  L.push(`  button_hover_fg = ${q(text.bright)},`)
  L.push(`  button_hover_bg = ${q(chrome.hover)},`)
  L.push('}')
  L.push('return M')
  return L.join('\n') + '\n'
}
