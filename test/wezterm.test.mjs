import test from 'node:test'
import assert from 'node:assert/strict'
import { build } from '../src/build.mjs'
import { selectionOpaque } from '../src/palette.mjs'

const cap = (s) => s[0].toUpperCase() + s.slice(1)
const { weztermLua, themeJson } = build()
const theme = JSON.parse(themeJson)

test('wezterm lua module shape', () => {
  assert.ok(weztermLua, 'build() must produce weztermLua')
  assert.match(weztermLua, /^-- Generated by build\.mjs/)
  assert.match(weztermLua, /M\.name = 'Midnight Lilac'/)
  assert.match(weztermLua, /M\.colors = \{/)
  assert.match(weztermLua, /M\.window_frame = \{/)
  assert.match(weztermLua, /return M\s*$/)
})

test('no alpha hex anywhere (wezterm parses only RRGGBB-family forms)', () => {
  assert.doesNotMatch(weztermLua, /#[0-9A-Fa-f]{8}\b/)
  assert.doesNotMatch(weztermLua, /#[0-9A-Fa-f]{4}\b/)
})

test('nightly-only keys never emitted', () => {
  for (const key of ['compose_fg', 'compose_bg', 'input_selector_label_bg', 'input_selector_label_fg',
    'launcher_label_bg', 'launcher_label_fg', 'inactive_tab_edge_hover']) {
    assert.ok(!weztermLua.includes(`${key} =`), `nightly key ${key} must not be emitted`)
  }
})

test('stable base keys present', () => {
  for (const key of ['foreground', 'background', 'cursor_bg', 'cursor_fg', 'cursor_border',
    'selection_fg', 'selection_bg', 'scrollbar_thumb', 'split', 'compose_cursor',
    'copy_mode_active_highlight_bg', 'quick_select_label_bg']) {
    assert.ok(weztermLua.includes(`\n  ${key} = `), `missing stable key: ${key}`)
  }
})

test('tab_bar groups use bg_color/fg_color field names', () => {
  assert.match(weztermLua, /tab_bar = \{/)
  for (const g of ['active_tab', 'inactive_tab', 'inactive_tab_hover', 'new_tab', 'new_tab_hover']) {
    assert.match(weztermLua, new RegExp(`${g} = \\{[\\s\\S]*?bg_color[\\s\\S]*?fg_color`), g)
  }
  assert.match(weztermLua, /inactive_tab_edge = /)
})

test('selection_bg is the pre-blended opaque equivalent', () => {
  assert.match(weztermLua, new RegExp(`selection_bg = '${selectionOpaque.hex6().toLowerCase()}'`))
})

test('ansi/brights byte-equal the theme terminal.ansi* values', () => {
  const names = ['black', 'red', 'green', 'yellow', 'blue', 'magenta', 'cyan', 'white']
  const block = (arr) => {
    const m = weztermLua.match(new RegExp(`${arr} = \\{([\\s\\S]*?)\\}`))
    assert.ok(m, `missing ${arr} array`)
    return [...m[1].matchAll(/'#([0-9a-f]{6})', -- ([\w ]+)/g)]
  }
  const ansi = block('ansi')
  const brights = block('brights')
  assert.equal(ansi.length, 8)
  assert.equal(brights.length, 8)
  names.forEach((n, i) => {
    assert.equal(`#${ansi[i][1]}`, theme.colors[`terminal.ansi${cap(n)}`].toLowerCase())
    assert.equal(ansi[i][2], n)
    assert.equal(`#${brights[i][1]}`, theme.colors[`terminal.ansiBright${cap(n)}`].toLowerCase())
  })
})
